def test_write_csv_contains_scores_and_bench_version(tmp_path):
    path = tmp_path / "test.csv"
    write_csv(_state(), path)
    assert path.is_file()
    text = path.read_text(encoding="utf-8")
    rows = {row[0]: (row[1] if len(row) > 1 else "") for row in csv.reader(text.splitlines())}
    assert rows["run_id"] == "unit-test-run"
    assert rows["cpu_single_primes_per_sec"] == "123.4"
    assert rows["status"] == "completed"
    assert rows["bench_version"] == BENCH_VERSION
    # bench_version sits right after run_id
    keys = list(rows)
    assert keys.index("bench_version") == keys.index("run_id") + 1


def test_json_state_roundtrip_keeps_bench_version(tmp_path):
    """Runner writes JSON via json.dump(state); the schema must keep bench_version."""
    path = tmp_path / "unit-test-run.json"
    state = _state()
    path.write_text(json.dumps(state, indent=2), encoding="utf-8")
    loaded = json.loads(path.read_text(encoding="utf-8"))
    assert loaded["bench_version"] == BENCH_VERSION
    assert loaded["bench_version"] == "1.2.1"
    assert loaded["run_id"] == "unit-test-run"


def test_write_xlsx_summary_and_sensors(tmp_path):
    openpyxl = pytest.importorskip("openpyxl")
    path = tmp_path / "test.xlsx"
    write_xlsx(_state(), path)
    assert path.is_file()
    wb = openpyxl.load_workbook(path)
    try:
        assert "Summary" in wb.sheetnames
        assert "Sensors" in wb.sheetnames
        summary = [cell.value for row in wb["Summary"].iter_rows() for cell in row]
        assert "run_id" in summary
        assert "unit-test-run" in summary
        assert "cpu_single_primes_per_sec" in summary
        assert "123.4" in summary or 123.4 in summary
        # XLSX reuses CSV rows, so bench_version is included here too.
        assert "bench_version" in summary
        assert BENCH_VERSION in summary
        sensors = wb["Sensors"]
        headers = [sensors.cell(1, c).value for c in range(1, 7)]
        assert headers == ["t", "cpu", "mem", "clock", "temp", "disk_mb_s"]
        assert sensors.cell(2, 1).value == "0" or sensors.cell(2, 1).value == 0
    finally:
        wb.close()


def test_write_all_reports_writes_html_and_csv(tmp_path):
    paths = write_all_reports(_state(), tmp_path)
    assert paths["html"].is_file()
    assert paths["csv"].is_file()
    # The runner writes the JSON; write_all_reports only lists it when it exists.
    assert "json" not in paths
    try:
        import openpyxl  # noqa: F401

        assert "xlsx" in paths
        assert paths["xlsx"].is_file()
    except ImportError:
        assert "xlsx" not in paths
    html = paths["html"].read_text(encoding="utf-8")
    assert "unit-test-run" in html
    assert f"Generated by Botlabs Bench {APP_VERSION}" in html
    assert f"<title>Botlabs Bench {APP_VERSION} - unit-test-run</title>" in html
    assert "Botlabs Bench 1.0 " not in html


def test_render_html_escapes_special_characters():
    html = render_html(_state(sysinfo={
        "computer_name": "PC <A> & 'B'",
        "cpu_name": "Test CPU",
        "cpu_physical_cores": 2,
        "cpu_logical_cores": 4,
        "ram_total_gb": 8,
        "ram_available_gb": 4,
        "os": "Linux",
        "os_release": "1",
        "os_build": "1",
        "gpus": ["Test GPU"],
        "disks": [],
    }))
    assert "unit-test-run" in html
    assert "PC <A>" not in html
    assert "PC &lt;A&gt; &amp; 'B'" in html
    assert _esc("<tag> & x") == "&lt;tag&gt; &amp; x"


def test_svg_line_empty_equal_range_and_nan():
    empty = _svg_line([], [], width=100, height=50)
    assert "<svg" in empty
    assert "No data" in empty

    same_x = _svg_line([1.0, 1.0, 1.0], [10.0, 20.0, 30.0])
    assert "<svg" in same_x
    assert "polyline" in same_x

    with_nan = _svg_line([0.0, 1.0, 2.0], [10.0, float("nan"), 30.0])
    assert "<svg" in with_nan
    assert "polyline" in with_nan
    # NaN should not appear in the point list
    assert "nan" not in with_nan.lower()
    assert math.isnan(float("nan"))
